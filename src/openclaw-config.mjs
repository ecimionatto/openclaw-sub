import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { PROVIDERS, detectBinary, inspectProvider } from "./providers.mjs";
import { getDefaultStateDir, getProviderCooldown, loadConfig, loadState } from "./state.mjs";

/**
 * Generates an OpenClaw-compatible CLI runner configuration and wrapper script
 * so OpenClaw routes primary and fallback model turns through `clawsub`.
 *
 * @param {{
 *   stateDir?: string,
 *   chain?: string[],
 *   workspace?: string,
 * }} [opts]
 */
export function generateOpenClawIntegration(opts = {}) {
  const stateDir = opts.stateDir || getDefaultStateDir();
  const config = loadConfig(stateDir);
  const chain = opts.chain || config.chain || ["claude", "codex", "agy"];
  const workspace = opts.workspace || config.workspace || process.cwd();

  const binDir = path.join(stateDir, "bin");
  fs.mkdirSync(binDir, { recursive: true });

  // Unified router shim: runs the full failover chain in one call
  const routerWrapperPath = path.join(binDir, "clawsub-router");
  const routerScript = `#!/usr/bin/env bash
# Generated by clawsub init — routes OpenClaw prompts across subscription CLIs (${chain.join(" -> ")})
set -euo pipefail
exec npx --yes openclaw-sub run "$@"
`;
  fs.writeFileSync(routerWrapperPath, routerScript, { mode: 0o755 });

  // Per-provider cooldown-aware shims for OpenClaw's native primary/fallback slots
  const providerShims = {};
  for (const providerId of chain) {
    if (!PROVIDERS[providerId]) continue;
    const shimPath = path.join(binDir, `clawsub-${providerId}`);
    const shimContent = `#!/usr/bin/env bash
# Generated by clawsub init — cooldown-aware headless wrapper for ${providerId}
set -euo pipefail
exec npx --yes openclaw-sub exec ${providerId} -- "$@"
`;
    fs.writeFileSync(shimPath, shimContent, { mode: 0o755 });
    providerShims[providerId] = shimPath;
  }

  const profilePath = path.join(stateDir, "openclaw-sub-profile.json");
  const profile = {
    generatedAt: new Date().toISOString(),
    mode: "subscription-cli",
    zeroApiKeys: true,
    workspace,
    primaryProvider: chain[0] || "claude",
    fallbackProviders: chain.slice(1),
    routerCommand: routerWrapperPath,
    providerShims,
    guardrails: {
      quietWindows: config.quietWindows,
      quotaReservationWindows: config.quotaReservationWindows,
      pauseHeartbeatsWhenAllCoolingDown: config.pauseHeartbeatsWhenAllCoolingDown,
    },
  };
  fs.writeFileSync(profilePath, JSON.stringify(profile, null, 2) + "\n", "utf8");

  return {
    profilePath,
    routerWrapperPath,
    providerShims,
    profile,
  };
}

/**
 * Reads and parses ~/.openclaw/openclaw.json. Returns null if absent or unreadable.
 * @param {string} [homeDir]
 * @returns {object|null}
 */
export function readOpenClawJson(homeDir) {
  const dir = homeDir || os.homedir();
  const jsonPath = path.join(dir, ".openclaw", "openclaw.json");
  try {
    return JSON.parse(fs.readFileSync(jsonPath, "utf8"));
  } catch (err) {
    if (err.code === "ENOENT") return null;
    throw err;
  }
}

const SESSION_CATALOG_PROVIDERS = ["anthropic", "codex"];

/**
 * Deep-merges `patch` into `base`, returning a new object.
 * Arrays are replaced, not merged.
 * @param {object} base
 * @param {object} patch
 * @returns {object}
 */
function deepMerge(base, patch) {
  const out = { ...base };
  for (const [k, v] of Object.entries(patch)) {
    if (v !== null && typeof v === "object" && !Array.isArray(v) && typeof base[k] === "object" && base[k] !== null && !Array.isArray(base[k])) {
      out[k] = deepMerge(base[k], v);
    } else {
      out[k] = v;
    }
  }
  return out;
}

const CLAWSUB_PATCH = {
  plugins: {
    entries: {
      anthropic: { config: { sessionCatalog: { enabled: false } } },
      codex: { config: { sessionCatalog: { enabled: false } } },
    },
  },
};

/**
 * Reads ~/.openclaw/openclaw.json, deep-merges clawsub-owned keys (sessionCatalog settings),
 * writes a timestamped backup if the file changes, then writes the merged result.
 * Second call is a no-op if the file already has the correct values.
 * @param {string} [homeDir]
 * @returns {{ changed: boolean, jsonPath: string, backupPath: string|null }}
 */
export function writeOpenClawJson(homeDir) {
  const dir = homeDir || os.homedir();
  const ocDir = path.join(dir, ".openclaw");
  const jsonPath = path.join(ocDir, "openclaw.json");

  let existing = {};
  let existingRaw = null;
  try {
    existingRaw = fs.readFileSync(jsonPath, "utf8");
    existing = JSON.parse(existingRaw);
  } catch (err) {
    if (err.code !== "ENOENT") throw err;
  }

  const merged = deepMerge(existing, CLAWSUB_PATCH);
  const mergedStr = JSON.stringify(merged, null, 2) + "\n";

  if (existingRaw !== null && mergedStr === JSON.stringify(JSON.parse(existingRaw), null, 2) + "\n") {
    return { changed: false, jsonPath, backupPath: null };
  }

  let backupPath = null;
  if (existingRaw !== null) {
    backupPath = path.join(ocDir, `openclaw.json.bak.${Date.now()}`);
    fs.writeFileSync(backupPath, existingRaw, "utf8");
  }

  fs.mkdirSync(ocDir, { recursive: true });
  fs.writeFileSync(jsonPath, mergedStr, "utf8");
  return { changed: true, jsonPath, backupPath };
}

/**
 * Validates an openclaw.json object for headless-safe settings.
 * Returns { issues, recommendations } arrays with human-readable strings.
 * @param {object} parsed
 * @returns {{ issues: string[], recommendations: string[] }}
 */
export function inspectOpenClawJson(parsed, opts = {}) {
  const issues = [];
  const recommendations = [];

  for (const providerId of SESSION_CATALOG_PROVIDERS) {
    const entryConfig = parsed?.plugins?.entries?.[providerId]?.config;
    if (entryConfig === undefined || entryConfig?.sessionCatalog?.enabled !== false) {
      const currentValue = entryConfig?.sessionCatalog?.enabled ?? "unset (defaults to enabled)";
      issues.push(
        `openclaw.json: plugins.entries.${providerId}.config.sessionCatalog.enabled must be false for headless/cron use (currently: ${currentValue}).`
      );
      recommendations.push(
        `Set plugins.entries.${providerId}.config.sessionCatalog.enabled = false in ~/.openclaw/openclaw.json`
      );
      recommendations.push(
        `openclaw models auth login --provider ${providerId} --force`
      );
    }
  }

  const homeDir = opts.homeDir || os.homedir();
  const loadPaths = Array.isArray(parsed?.plugins?.load?.paths) ? parsed.plugins.load.paths : [];
  for (const p of loadPaths) {
    if (typeof p !== "string") continue;
    const expanded = p.startsWith("~") ? path.join(homeDir, p.slice(1)) : p;
    if (!fs.existsSync(expanded)) {
      issues.push(
        `openclaw.json: plugins.load.paths entry does not exist: ${p}. Update plugins.load.paths to valid plugin load paths.`
      );
    }
  }

  const hasAgyCli = loadPaths.some((p) => typeof p === "string" && p.includes("agy-cli"));
  if (!hasAgyCli) {
    issues.push(
      "openclaw.json: plugins.load.paths does not include an agy-cli plugin path."
    );
    recommendations.push(
      "Add the agy-cli plugin path to plugins.load.paths in ~/.openclaw/openclaw.json."
    );
  }

  return { issues, recommendations };
}

/**
 * Runs a comprehensive health and readiness check (`clawsub doctor`).
 * @param {{ stateDir?: string, homeDir?: string, now?: Date }} [opts]
 */
export function runDoctor(opts = {}) {
  const stateDir = opts.stateDir || getDefaultStateDir();
  const config = loadConfig(stateDir);
  const state = loadState(stateDir);
  const now = opts.now || new Date();

  const openclawBin = detectBinary("openclaw");
  const chain = config.chain || ["claude", "codex", "agy"];
  const providers = chain.map((id) => {
    const info = inspectProvider(id, { homeDir: opts.homeDir });
    const cooldown = getProviderCooldown(state, id, now);
    return {
      ...info,
      coolingDown: cooldown.coolingDown,
      cooldownUntil: cooldown.until,
      remainingMinutes: cooldown.remainingMinutes,
    };
  });

  const installedReady = providers.filter((p) => p.installed && p.authenticated);
  const issues = [];
  const recommendations = [];

  if (!openclawBin.installed) {
    issues.push("OpenClaw binary (`openclaw`) was not found on PATH.");
    recommendations.push("Install OpenClaw (`npm install -g openclaw`) or add it to PATH.");
  }

  if (installedReady.length === 0) {
    issues.push("No authenticated subscription CLIs found in the configured chain.");
    recommendations.push(
      "Log into at least one subscription CLI (`claude login`, `codex login`, or `agy`)."
    );
  } else if (installedReady.length === 1) {
    recommendations.push(
      `Only 1 subscription CLI (${installedReady[0].id}) is ready. Add a free-tier fallback like Google Gemini/Antigravity (\`agy\`) or local \`ollama\` so 5-hour quota windows never take your bot offline.`
    );
  }

  for (const p of providers) {
    if (!p.installed) {
      issues.push(`${p.name} (\`${p.binary}\`) is not installed. Install: ${p.installHint}`);
    } else if (!p.authenticated) {
      issues.push(`${p.name} (\`${p.binary}\`) is installed but not logged in. Run: ${p.loginHint}`);
    }
    for (const w of p.warnings || []) {
      recommendations.push(`[${p.id}] ${w}`);
    }
  }

  for (const [pid, pst] of Object.entries(state.providers || {})) {
    if (pst.status === "auth_expired") {
      issues.push(`${pid}: auth_expired — credentials invalid or expired.`);
      recommendations.push(`openclaw models auth login --provider ${pid} --force`);
    }
  }

  let openclawJson = null;
  try {
    const parsedOcJson = readOpenClawJson(opts.homeDir);
    if (parsedOcJson !== null) {
      openclawJson = inspectOpenClawJson(parsedOcJson, { homeDir: opts.homeDir });
      issues.push(...openclawJson.issues);
      recommendations.push(...openclawJson.recommendations);
    }
  } catch (err) {
    const readErr = `openclaw.json: could not read or parse: ${err.message}`;
    issues.push(readErr);
    openclawJson = { issues: [readErr], recommendations: [] };
  }

  return {
    ok: issues.length === 0 && installedReady.length > 0,
    openclaw: openclawBin,
    config,
    providers,
    issues,
    recommendations,
    openclawJson,
  };
}
